"""Generates stubs/PreviewMetrics.h (glyph advances) and stubs/I18n.h
(English strings) for the host preview build."""
import os
import re

from PIL import ImageFont

from fonts import FONTS, ROOT, ppem, ttf

HERE = os.path.dirname(os.path.abspath(__file__))
EXTRA = ['\u00b0', '\u2026', '\u2022', '\u00b7', '\u2014']
CHARS = [chr(c) for c in range(32, 127)] + EXTRA

out = ['#pragma once', '// generated by gen_stubs.py', '#include <cstdint>', '', '#include "fontIds.h"', '',
       'struct PreviewFont { int id; int lineHeight; int ascender; const char* name; '
       'const uint8_t* adv[3]; };  // R, B, I', '']
entries = []
for name, (macro, size, lh, asc, files) in FONTS.items():
    arrays = []
    for style in 'RBI':
        font = ImageFont.truetype(ttf(name, style), round(ppem(name)))
        adv = [min(255, round(font.getlength(c))) for c in CHARS]
        arr = f'k{name}_{style}'
        out.append(f'static const uint8_t {arr}[] = {{{", ".join(map(str, adv))}}};')
        arrays.append(arr)
    entries.append(f'  {{{macro}, {lh}, {asc}, "{name}", {{{", ".join(arrays)}}}}},')
out.append('')
out.append('// index: ASCII 32..126, then the EXTRA codepoints below')
out.append('static const uint32_t kPreviewExtra[] = {' + ', '.join(hex(ord(c)) for c in EXTRA) + '};')
out.append('static const PreviewFont kPreviewFonts[] = {')
out += entries
out.append('};')
with open(os.path.join(HERE, 'stubs', 'PreviewMetrics.h'), 'w') as f:
    f.write('\n'.join(out) + '\n')

# I18n: every key in english.yaml.
keys = []
values = []
with open(os.path.join(ROOT, 'lib', 'I18n', 'translations', 'english.yaml'), encoding='utf-8') as f:
    for line in f:
        m = re.match(r'^(STR_[A-Z0-9_]+):\s*"(.*)"\s*$', line)
        if m:
            keys.append(m.group(1))
            values.append(m.group(2))
i18n = ['#pragma once', '// generated by gen_stubs.py', '#include <cstdint>', '',
        'enum class StrId : uint16_t {']
i18n += [f'  {k},' for k in keys]
i18n += ['  _COUNT', '};', '', 'class I18n {', ' public:',
         '  static I18n& getInstance() { static I18n i; return i; }',
         '  const char* get(StrId id) const {', '    static const char* const S[] = {']
i18n += ['      "' + v + '",' for v in values]  # YAML values are already C-escaped
i18n += ['    };', '    return S[static_cast<uint16_t>(id)];', '  }', '};', '',
         '#define tr(id) I18n::getInstance().get(StrId::id)', '#define I18N I18n::getInstance()']
with open(os.path.join(HERE, 'stubs', 'I18n.h'), 'w') as f:
    f.write('\n'.join(i18n) + '\n')
print('stubs generated:', len(keys), 'strings')
