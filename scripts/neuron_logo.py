"""Convert the Nautical Neuron logo PNG into the 1-bit C array used by the
boot and sleep screens.

Usage: python scripts/neuron_logo.py [src/images/neuron_logo.png] [size]

The logo is fitted into a size x size square (size must be a multiple of 8),
thresholded to pure black/white and rotated 90 degrees counter-clockwise into
the panel's native orientation (same layout as scripts/convert_icon.py).
"""
import os
import sys

from PIL import Image

THRESHOLD = 170  # anything darker than this (incl. the red line art) becomes ink


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(root, 'src', 'images', 'neuron_logo.png')
    size = int(sys.argv[2]) if len(sys.argv) > 2 else 336
    if size % 8:
        sys.exit('size must be a multiple of 8')

    img = Image.open(src).convert('RGBA')
    flat = Image.new('RGBA', img.size, (255, 255, 255, 255))
    flat.paste(img, mask=img.split()[3])
    gray = flat.convert('L')
    scale = size / max(img.size)
    w, h = round(img.size[0] * scale), round(img.size[1] * scale)
    gray = gray.resize((w, h), Image.LANCZOS)
    canvas = Image.new('L', (size, size), 255)
    canvas.paste(gray, ((size - w) // 2, (size - h) // 2))
    canvas = canvas.rotate(90, expand=True)

    px = canvas.load()
    packed = []
    for y in range(size):
        for x in range(0, size, 8):
            byte = 0
            for b in range(8):
                if px[x + b, y] >= THRESHOLD:  # 1 = white, 0 = ink
                    byte |= 1 << (7 - b)
            packed.append(byte)

    out = ['#pragma once', '#include <cstdint>', '',
           '// Nautical Neuron crest, generated by scripts/neuron_logo.py',
           f'static constexpr int NEURON_LOGO_SIZE = {size};',
           'static const uint8_t NeuronLogo[] = {']
    for i in range(0, len(packed), 16):
        out.append('    ' + ', '.join(f'0x{v:02X}' for v in packed[i:i + 16]) + ',')
    out.append('};')
    dest = os.path.join(root, 'src', 'images', 'NeuronLogo.h')
    with open(dest, 'w') as f:
        f.write('\n'.join(out) + '\n')
    print(f'Wrote {dest} ({size}x{size}, {len(packed)} bytes)')


if __name__ == '__main__':
    main()
